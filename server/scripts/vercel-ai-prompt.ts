/**
 * Generates api/_ai-prompt.ts — the AI consultant's system prompts (uz, ru) for the Vercel chat function,
 * built from the bundled catalog with the same builder the Node server uses.
 * Run after changing src/data/content.json:  npx tsx server/scripts/vercel-ai-prompt.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { buildSystemPrompt, type ClientsInfo } from '../src/ai/prompt.js'
import type { Content } from '../src/schemas.js'

const root = new URL('../../', import.meta.url)
const content = JSON.parse(readFileSync(new URL('src/data/content.json', root), 'utf8')) as Content
const clients = JSON.parse(readFileSync(new URL('src/data/clients.json', root), 'utf8')) as ClientsInfo
const out = `// GENERATED by server/scripts/vercel-ai-prompt.ts — do not edit by hand.
export const SYSTEM_PROMPT: Record<'uz' | 'ru', string> = ${JSON.stringify({ uz: buildSystemPrompt(content, 'uz', clients), ru: buildSystemPrompt(content, 'ru', clients) }, null, 2)}

export const PRODUCTS: { name: string; slug: string }[] = ${JSON.stringify(content.products.map((p) => ({ name: p.name, slug: p.slug })))}
`
writeFileSync(new URL('api/_ai-prompt.ts', root), out)
console.log('api/_ai-prompt.ts', out.length, 'bytes')
